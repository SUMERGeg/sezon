import { expect, test } from "@playwright/test";

test("кастомная сортировка: keyboard, Escape, outside click, typeahead и Tab", async ({ page }, testInfo) => {
  const errors: string[] = [];
  page.on("pageerror", (error) => errors.push(error.message));
  await page.goto("/shop");
  const sort = page.getByRole("combobox", { name: "Сортировка", exact: true });
  await sort.focus();
  await page.keyboard.press("ArrowDown");
  const list = page.getByRole("listbox", { name: "Сортировка", exact: true });
  await expect(list).toBeVisible();
  await expect(list.getByRole("option", { name: "Рекомендуемые" })).toHaveAttribute("aria-selected", "true");
  await page.screenshot({ path: testInfo.outputPath("sort-dropdown.png"), fullPage: false });
  await page.keyboard.press("ArrowDown");
  await page.keyboard.press("Enter");
  await expect(sort).toContainText("Цена по возрастанию");
  await expect(sort).toBeFocused();
  await expect(page).toHaveURL(/sort=price-asc/);
  await page.keyboard.press("Enter");
  await page.keyboard.press("ArrowDown");
  await page.keyboard.press("Escape");
  await expect(list).not.toBeVisible();
  await expect(sort).toContainText("Цена по возрастанию");
  await sort.click();
  await page.getByRole("heading", { name: "Букеты и композиции", exact: true }).click();
  await expect(list).not.toBeVisible();
  await sort.focus();
  await sort.dispatchEvent("keydown", { key: "н", code: "KeyY" });
  await expect(sort).toContainText("Новинки коллекции");
  await page.keyboard.press("Home");
  await page.keyboard.press("Enter");
  await expect(sort).toContainText("Рекомендуемые");
  await page.keyboard.press("Enter");
  await page.keyboard.press("ArrowDown");
  await page.keyboard.press("Tab");
  await expect(sort).toContainText("Цена по возрастанию");
  await expect(sort).not.toBeFocused();
  await expect(list).not.toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  expect(errors).toEqual([]);
});
